	// This entire fix was found by setsid
	// https://github.com/setsid/bo2-ps3-psn-freeze-fix
	// All credit goes to him
	void PerformNOP(u32 address)
	{
		u8 functionOverwrite[] = { 0x60, 0x00, 0x00, 0x00 };
		WriteProcessMemory(sys_process_getpid(), (void*)address, functionOverwrite, sizeof(functionOverwrite));
	}

	void Main()
	{
		// Check if we're in SP/EBOOT first
		u32 spLoaded = LoaderCommon::FindFunctionAddress(spPatchAddress, spSignature, spSignatureLength, 512); // Scanning should be unnecessary. Just take a lower value like 512.
		if (spLoaded != 0) {
			PerformNOP(spPatchAddress);
			printf("[CODPatch Loader] Patched BO2 sp/eboot NOP at %08X\n", spPatchAddress);
			return;
		}

		u32 mpLoaded = LoaderCommon::FindFunctionAddress(mpPatchAddress, mpSignature, mpSignatureLength, 512); 
		if (mpLoaded != 0) {
			PerformNOP(mpPatchAddress);
			printf("[CODPatch Loader] Patched BO2 mp NOP at %08X\n", mpPatchAddress);
			return;
		}

		printf("[CODPatch Loader] BO2 Main() couldn't find either mp or eboot/sp instructions to NOP.\n");
	}
